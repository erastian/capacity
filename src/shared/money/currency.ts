const ZERO_DECIMALS = new Set(['BIF', 'CLP', 'DJF', 'GNF', 'ISK', 'JPY', 'KMF', 'KRW', 'PYG', 'RWF', 'UGX', 'VND', 'VUV', 'XAF', 'XOF', 'XPF']);

const THREE_DECIMALS = new Set(['BHD', 'IQD', 'JOD', 'KWD', 'LYD', 'OMR', 'TND']);

const MINOR_UNITS: ReadonlyMap<string, number> = new Map(ISO_4217.map((code) => [code, ZERO_DECIMALS.has(code) ? 0 : THREE_DECIMALS.has(code) ? 3 : 2]));

export function isCurrency(code: string): boolean {
  return MINOR_UNITS.has(code);
}

export function minorUnits(code: string): number {
  const units = MINOR_UNITS.get(code);
  if (units === undefined) {
    throw new Error(`Unknown currency ${code}`);
  }
  return units;
}
